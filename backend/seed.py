def vf(value, status="Verified", source=None):
    return {"value": value, "status": status, "source": source, "note": None}


def prog(pid, name, degree, field, dur, tuition, living, deadline, min_gpa, ielts, toefl,
         intake, sch, lang="English", tstat="Verified", src="University official site"):
    return {
        "id": pid, "name": name, "degree": degree, "field": field, "duration_years": dur,
        "language": lang,
        "tuition_per_year": vf(tuition, tstat, src),
        "living_cost_per_year": vf(living, "Estimated", "Numbeo cost-of-living estimate"),
        "intake": intake,
        "application_deadline": vf(deadline, "Verified", src),
        "requirements": {
            "min_gpa": vf(min_gpa, "Verified", src) if min_gpa is not None else None,
            "ielts": vf(ielts, "Verified", src) if ielts is not None else None,
            "toefl": vf(toefl, "Verified", src) if toefl is not None else None,
            "other": None,
        },
        "scholarship_ids": sch,
    }


